# =============================================================================
# Dossier apps/ - Toutes nos applications Django regroupées ici
# =============================================================================
# Au fur et à mesure du projet, on créera des sous-dossiers comme :
#   apps/flotte/      -> gestion des camions et chauffeurs
#   apps/missions/    -> gestion des missions et trajets
#   apps/simulation/  -> moteur de simulation et événements
#   apps/finances/    -> budget, dépenses, rentabilité
#   apps/geographie/  -> villes, routes, points GPS de Madagascar
#
# Pourquoi regrouper dans apps/ au lieu de mettre les apps à la racine ?
#   - Plus propre : la racine reste lisible
#   - Évite les conflits de noms avec des packages Python externes
#   - Pattern standard utilisé dans les projets Django professionnels
